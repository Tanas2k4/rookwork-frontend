/**
 * Renders an emoji character with a robust cross-platform font stack 
 * ensuring beautiful color emojis on Windows, macOS, Linux, and mobile devices.
 */
export function EmojiChar({ emoji, size = 18 }: { emoji: string; size?: number }) {
  return (
    <span
      role="img"
      aria-label={emoji}
      style={{
        fontFamily:
          '"Apple Color Emoji", "Segoe UI Emoji", "Noto Color Emoji", "Twemoji Mozilla", "Android Emoji", sans-serif',
        fontSize: size,
        lineHeight: 1,
        fontStyle: "normal",
        userSelect: "none",
        display: "inline-block",
      }}
    >
      {emoji}
    </span>
  );
}

